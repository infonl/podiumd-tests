"""Write docs/test-overview.md: how many tests each tier, area, source and known issue has.

Counts come from pytest's collection of tests/ (no environment needed; a parametrized case counts as one test) and
from the unit tests and perf endpoints. `--check` fails when the file is out of date (run_python_checks).
"""

from __future__ import annotations

import ast
import contextlib
import io
import re
import sys

from collections import Counter
from dataclasses import dataclass
from typing import TYPE_CHECKING

import pytest

from podiumd_tests.config import REPO_ROOT
from podiumd_tests.perf.runs import ENDPOINTS
from podiumd_tests.tiers import TIERS

if TYPE_CHECKING:
    from collections.abc import Generator
    from collections.abc import Iterable
    from pathlib import Path

OUT = REPO_ROOT / "docs" / "test-overview.md"
TIER_ORDER = ("smoke", "component", "integration", "perf", "chaos")
# tests/<tier>/<area>/<module>; a module straight under the tier is its own area.
AREA_DEPTH = 4
KNOWN_ISSUE = re.compile(r"^\[([a-z0-9-]+)\]")
LINKS = (
    ("docs/draaiboek-coverage.md", "per case of the PodiumD test draaiboek, which test covers it"),
    ("docs/research/zac-scenario-gaps.md", "per scenario of the ZAC team, gap, partial or covered"),
    ("MIGRATION.md", "per test of the merged suites, ported, merged or dropped"),
    ("docs/research/upstream-tests.md", "what the components' own tests could still add"),
    ("results/README.md", "what a run's outcomes mean; each run's summary.md and report.html"),
)
HEADER = """# Test overview

Generated by `python -m podiumd_tests.overview` from the tests' markers; `run_python_checks` fails when it is
out of date. Scenarios: test functions, each with one scenario. Tests: the runs pytest collects; a scenario with
parameters (one run per role, say) counts once per parameter, so Tests is at least Scenarios.
Expected failures: cases with an xfail marker naming a known issue; a fixture that marks a test only on some
versions is not counted.
"""


@dataclass(frozen=True)
class Case:
    """One collected test case."""

    tier: str
    area: str
    function: str
    origins: tuple[str, ...]
    known_issues: tuple[str, ...]
    has_scenario: bool
    destructive: bool


def area_of(parts: tuple[str, ...]) -> str:
    """Return a test's area: its directory under the tier, else its module without test_."""
    if len(parts) >= AREA_DEPTH:
        return parts[2]
    module = parts[-1]
    return module.removesuffix(".py").removeprefix("test_")


def case_of(item: pytest.Item) -> Case:
    """Return the overview's view of a collected test."""
    parts = item.path.relative_to(REPO_ROOT).parts
    sources = [str(marker.args[0]) for marker in item.iter_markers("source") if marker.args]
    origins = tuple(source.split()[0] for source in sources)
    reasons = [str(marker.kwargs.get("reason", "")) for marker in item.iter_markers("xfail")]
    known_issues = tuple(found.group(1) for found in map(KNOWN_ISSUE.match, reasons) if found)
    name = getattr(item, "originalname", item.name)
    return Case(
        tier=parts[1],
        area=area_of(parts),
        function=f"{parts[-1]}::{name}",
        origins=origins,
        known_issues=known_issues,
        has_scenario=item.get_closest_marker("scenario") is not None,
        destructive=item.get_closest_marker("destructive") is not None,
    )


class Collector:  # pylint: disable=too-few-public-methods  # a pytest plugin with one hook
    """pytest plugin: records the collected items, then ends the session before any test runs."""

    def __init__(self) -> None:
        self.cases: list[Case] = []

    @pytest.hookimpl(wrapper=True)
    def pytest_collection_modifyitems(self, items: list[pytest.Item]) -> Generator[None]:
        """Record the items before podiumd-tests' own hook, which needs an environment."""
        self.cases = [case_of(item) for item in items]
        pytest.exit("collected", returncode=0)
        yield  # pragma: no cover  # pytest.exit raises


def collect() -> list[Case]:
    """Return every test case under tests/."""
    collector = Collector()
    # The collection lists every test on stdout; the overview is the output.
    with contextlib.redirect_stdout(io.StringIO()):
        pytest.main(["--collect-only", "-q", "-p", "no:cacheprovider", str(REPO_ROOT / "tests")], plugins=[collector])
    return collector.cases


def unit_test_count(directory: Path) -> int:
    """Return the number of test functions in the unit tests (a parametrized one counts once)."""
    count = 0
    for path in sorted(directory.glob("test_*.py")):
        nodes = ast.walk(ast.parse(path.read_text(encoding="utf-8")))
        count += sum(isinstance(node, ast.FunctionDef) and node.name.startswith("test_") for node in nodes)
    return count


def issue_key(issue: str) -> tuple[str, int]:
    """Return the sort key of a known-issue id: component, then number (open-zaak-2 before open-zaak-10)."""
    component, _, number = issue.rpartition("-")
    return component, int(number) if number.isdigit() else 0


def _table(header: tuple[str, ...], rows: Iterable[tuple[object, ...]]) -> list[str]:
    lines = [f"| {' | '.join(header)} |", f"|{' --- |' * len(header)}"]
    lines.extend(f"| {' | '.join(str(cell) for cell in row)} |" for row in rows)
    return [*lines, ""]


def _scenarios(cases: Iterable[Case]) -> int:
    return len({case.function for case in cases})


def _tier_rows(cases: list[Case], tiers: list[str]) -> list[tuple[object, ...]]:
    rows: list[tuple[object, ...]] = []
    for tier in tiers:
        of_tier = [case for case in cases if case.tier == tier]
        expected = sum(bool(case.known_issues) for case in of_tier)
        rows.append((tier, len(of_tier), _scenarios(of_tier), expected))
    # The full tier: its paths, without the destructive tests.
    full_tiers = {path.removeprefix("tests/") for path in TIERS["full"].paths}
    full = [case for case in cases if case.tier in full_tiers and not case.destructive]
    rows.append(("**full tier**", f"**{len(full)}**", f"**{_scenarios(full)}**", ""))
    return rows


def _area_rows(cases: list[Case], tiers: list[str]) -> list[tuple[object, ...]]:
    def order(key: tuple[str, str]) -> tuple[int, str]:
        return tiers.index(key[0]), key[1]

    keys = sorted({(case.tier, case.area) for case in cases}, key=order)
    rows: list[tuple[object, ...]] = []
    for tier, area in keys:
        of_area = [case for case in cases if (case.tier, case.area) == (tier, area)]
        rows.append((tier, area, len(of_area), _scenarios(of_area)))
    return rows


def render(cases: list[Case], unit_tests: int, perf_endpoints: int) -> str:
    """Return the overview as Markdown."""
    tiers = [tier for tier in TIER_ORDER if any(case.tier == tier for case in cases)]
    origins = Counter(case.origins[0] if case.origins else "-" for case in cases)
    known_issues: Counter[str] = Counter(issue for case in cases for issue in case.known_issues)
    by_issue = sorted(known_issues, key=issue_key)
    without_scenario = sum(not case.has_scenario for case in cases)
    lines = [HEADER, "## Per tier", ""]
    lines += _table(("Tier", "Tests", "Scenarios", "Expected failures"), _tier_rows(cases, tiers))
    lines += [
        f"Unit tests (`unit_tests/`, functions): {unit_tests}. Perf endpoints (`perf/runs.py`): {perf_endpoints}."
    ]
    lines += ["", "## Per area", ""]
    lines += _table(("Tier", "Area", "Tests", "Scenarios"), _area_rows(cases, tiers))
    lines += ["## Per source", "", "The origin of each test's first source marker (`sources.ORIGINS`).", ""]
    lines += _table(("Origin", "Tests"), sorted(origins.items()))
    lines += ["## Expected failures per known issue", "", "Ids of infonl/podiumd-known-issues.", ""]
    lines += _table(("Known issue", "Tests"), [(issue, known_issues[issue]) for issue in by_issue])
    lines += [f"Tests without a scenario: {without_scenario}.", ""]
    lines += ["## Coverage elsewhere", ""]
    for path, what in LINKS:
        link = (REPO_ROOT / path).relative_to(OUT.parent, walk_up=True)
        lines.append(f"- [{path}]({link}): {what}.")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    """Write the overview, or with --check report whether it is current."""
    text = render(collect(), unit_test_count(REPO_ROOT / "unit_tests"), len(ENDPOINTS))
    if "--check" not in argv:
        OUT.write_text(text, encoding="utf-8")
        print(OUT)
        return 0
    if OUT.read_text(encoding="utf-8") == text:
        return 0
    print(f"{OUT.relative_to(REPO_ROOT)} is out of date: run python -m podiumd_tests.overview")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
